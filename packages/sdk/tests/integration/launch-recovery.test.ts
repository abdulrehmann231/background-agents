import { randomUUID } from "node:crypto"
import { afterAll, beforeAll, describe, expect, it } from "vitest"
import { Daytona, type Sandbox } from "@daytonaio/sdk"
import { createSandboxJobs } from "@background-agents/sandbox-jobs"
import type { CodeAgentSandbox } from "../../src/types/provider"
import type { AgentDefinition } from "../../src/core/agent"
import { createBackgroundSession, writeInitialSessionMeta } from "../../src/background/session"

// Explicit opt-in: reuse an isolated QA sandbox, never allocate or delete one.
const sandboxId = process.env.SANDBOX_JOB_TEST_ID
const enabled = !!sandboxId && !!process.env.DAYTONA_API_KEY
describe.skipIf(!enabled)("durable launch protocol on an existing QA sandbox", () => {
  const root = `/tmp/codeagent-launch-qa-${randomUUID()}`
  const attempts: Array<{ id: string; root: string }> = []
  let sandbox: Sandbox
  const daytona = new Daytona({ apiKey: process.env.DAYTONA_API_KEY ?? "unused" })
  beforeAll(async () => { sandbox = await daytona.get(sandboxId!); await sandbox.start(60) }, 90_000)
  afterAll(async () => {
    if (!sandbox) return
    const jobs = createSandboxJobs(sandbox)
    for (const attempt of attempts) await jobs.abort(attempt.id, attempt.root)
    // The directory is generated by this test; no repository/user files live here.
    const result = await sandbox.process.executeCommand(`rm -rf '${root}'`)
    expect(result.exitCode).toBe(0)
  }, 90_000)

  function adapted(loseResponse = false): CodeAgentSandbox {
    const processAdapter = { process: { executeCommand: async (...args: Parameters<Sandbox["process"]["executeCommand"]>) => {
      const result = await sandbox.process.executeCommand(...args)
      if (loseResponse && args[0].includes("setsid ")) { loseResponse = false; throw new Error("Controlled lost launch response") }
      return result
    } } } as unknown as Sandbox
    return {
      jobs: createSandboxJobs(processAdapter), ensureProvider: async () => {}, setEnvVars: () => {},
      executeCommand: async (command, timeout) => {
        const result = await sandbox.process.executeCommand(command, undefined, undefined, timeout)
        return { exitCode: result.exitCode ?? -1, output: result.result ?? "" }
      },
    }
  }
  const agent: AgentDefinition = { name: "launch-test", toolMappings: {},
    buildCommand: () => ({ cmd: "sh", args: ["-c", "echo owned-start; sleep 20"] }), parse: () => null }

  it("recovers a lost launch response and cancels the same real process from cold", async () => {
    const dir = `${root}/lost-response`
    const initial = adapted(true)
    await writeInitialSessionMeta(initial, dir, agent.name, null)
    const meta = JSON.parse((await initial.executeCommand!(`cat '${dir}/meta.json'`)).output) as { jobId: string }
    attempts.push({ id: meta.jobId, root: dir })
    await expect(createBackgroundSession(agent, initial, dir).start("one")).rejects.toThrow("Controlled lost launch response")
    const cold = createBackgroundSession(agent, adapted(), dir)
    expect((await cold.getSnapshot()).running).toBe(true)
    await cold.start("one") // same known attempt, not a new command
    const handle = await adapted().jobs!.attach(meta.jobId, dir)
    expect(handle).not.toBeNull()
    expect((await adapted().jobs!.read(handle!, 0)).raw).toBe("owned-start\n")
    await expect(adapted().jobs!.start({ jobId: meta.jobId, root: dir, command: "echo different-work" })).rejects.toThrow(/different command/)
    await cold.cancel()
    expect(await createBackgroundSession(agent, adapted(), dir).getSnapshot()).toMatchObject({ running: false, runPhase: "stopped" })
  }, 60_000)

  it("fences a never-started session and rejects its late launcher", async () => {
    const dir = `${root}/never-started`
    const adapter = adapted()
    await writeInitialSessionMeta(adapter, dir, agent.name, null)
    const meta = JSON.parse((await adapter.executeCommand!(`cat '${dir}/meta.json'`)).output) as { jobId: string }
    attempts.push({ id: meta.jobId, root: dir })
    const delayed = createBackgroundSession(agent, adapter, dir)
    expect(await delayed.getSnapshot()).toMatchObject({ runPhase: "idle", launchPreparedAt: expect.any(String) })
    await createBackgroundSession(agent, adapted(), dir).cancel()
    await expect(delayed.start("must not run")).rejects.toThrow(/cancelled/)
    expect(await adapter.jobs!.attach(meta.jobId, dir)).toBeNull()
    expect(await createBackgroundSession(agent, adapted(), dir).getSnapshot()).toMatchObject({ running: false, runPhase: "stopped" })
  }, 45_000)

  it("serializes concurrent launch requests against an abort fence", async () => {
    const dir = `${root}/concurrent`
    const id = randomUUID()
    attempts.push({ id, root: dir })
    const options = { jobId: id, root: dir, command: "echo once; sleep 20" }
    const results = await Promise.allSettled([
      createSandboxJobs(sandbox).start(options), createSandboxJobs(sandbox).start(options),
      createSandboxJobs(sandbox).abort(id, dir),
    ])
    expect(results[2].status).toBe("fulfilled")
    await expect(createSandboxJobs(sandbox).start(options)).rejects.toThrow(/cancelled/)
    const job = await createSandboxJobs(sandbox).attach(id, dir)
    if (job) expect((await createSandboxJobs(sandbox).status(job)).alive).toBe(false)
  }, 60_000)

  it("does not mistake unreadable metadata for a stopped real process", async () => {
    const dir = `${root}/corrupt-record`
    const adapter = adapted()
    await writeInitialSessionMeta(adapter, dir, agent.name, null)
    const session = createBackgroundSession(agent, adapter, dir)
    const turn = await session.start("one")
    attempts.push({ id: turn.executionId, root: dir })
    const handle = (await adapter.jobs!.attach(turn.executionId, dir))!
    const metaPath = `${handle.dir}/meta.json`
    const original = await adapter.executeCommand!(`cat '${metaPath}'`)
    try {
      expect((await adapter.executeCommand!(`: > '${metaPath}'`)).exitCode).toBe(0)
      await expect(createBackgroundSession(agent, adapted(), dir).getSnapshot()).rejects.toThrow(/metadata/)
      await expect(createBackgroundSession(agent, adapted(), dir).cancel()).rejects.toThrow(/metadata/)
      expect((await adapter.jobs!.status(handle)).alive).toBe(true)
    } finally {
      const encoded = Buffer.from(original.output, "utf8").toString("base64")
      expect((await adapter.executeCommand!(`printf %s '${encoded}' | base64 -d > '${metaPath}'`)).exitCode).toBe(0)
      await adapter.jobs!.abort(turn.executionId, dir)
    }
  }, 60_000)
})
